    public function saveToTxt(Request $request)
    {
        $validated = $request->validate([
            'name' => 'required|string|max:255',
            'email' => 'required|email|max:255',
            'content' => 'required|string|max:5000',
        ]);

        Storage::disk('local')->append(
            'Contact.txt',
            "Naam: {$validated['name']}\nEmail: {$validated['email']}\nBericht: {$validated['content']}\n---\n"
        );

        return redirect()->route('homepage')->with('success', 'Bedankt voor je bericht!');
    }
